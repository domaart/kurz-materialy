# Cvičení 1 – For versus while
# Ke každému zadání si za pomlčku dopiš for, nebo while, a proč sis ho
# vybrala. Ptej se sama sebe: vím dopředu, kolikrát se to má zopakovat?

# 1)  Zatluč do prkna 10 hřebíků. - for, známe počet
# 2)  Buš kladivem do hřebíku, dokud není úplně zatlučený. - while, nevíme kolik
# 3)  Zahřívej vodu, dokud se nezačne vařit. - while, nevíme kolik
# 4)  Házej mincí, dokud nepadne panna. - while, nevíme kolik
# 5)  Házej kostkou, dokud šestka nepadne potřetí. - while, nevíme kolik
# 6)  Zeptej se uživatelky na číslo a tolikrát hoď kostkou. - for, známe počet
# 7)  Hoď kostkou a vypiš, co padlo. - while, nevíme kolik, ŽÁDNÝ CYKLUS
# 8)  Vypiš sudá čísla od 0 do 100. - for, známe počet
# 9)  Vypiš sudá čísla od 0 do čísla, které zadá uživatelka. - for, známe počet
# 10) Vypiš každé písmeno slova "Praha". - for, známe počet
# 11) Přidávej do košíku jablka, dokud košík neváží aspoň 2 kg. - while, nevíme kolik
# 12) Projdi 30 odpovědí v testu a spočítej, kolik jich je správně. - for, známe počet
